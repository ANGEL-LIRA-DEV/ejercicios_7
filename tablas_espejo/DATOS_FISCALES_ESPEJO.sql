ALTER SESSION SET CURRENT_SCHEMA = SECURITY;

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE DATOS_FISCALES_ESPEJO CASCADE CONSTRAINTS ';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TRIGGER TRG_DATOS_FISCALES_ESPEJO';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- Funcion para obtener IP
CREATE OR REPLACE FUNCTION FN_GET_IP
RETURN VARCHAR2
IS
BEGIN
    RETURN NVL(SYS_CONTEXT('USERENV', 'IP_ADDRESS'), SYS_CONTEXT('USERENV', 'HOST'));
    EXCEPTION
        WHEN OTHERS THEN
            RETURN 'LOCALHOST';
END FN_GET_IP;
/

-- Creacion de tabla espejo
CREATE TABLE DATOS_FISCALES_ESPEJO (
    UUID_DATOS_FISCALES_ESPEJO VARCHAR2(36) NOT NULL,
    ID_DATOSFISC VARCHAR2(36) NOT NULL,
    ID_CLIENTE VARCHAR2(36) NOT NULL,
    RAZON_SOCIAL VARCHAR2(150) NOT NULL,
    RFC VARCHAR2(13) NOT NULL,
    CODIGO_POSTAL VARCHAR2(5) NOT NULL,
    ID_TIPO_CLIENTE VARCHAR2(3) NOT NULL,
    USO_CFDI VARCHAR2(3) NOT NULL,
    EMAIL VARCHAR2(100),
    D_ESTADO VARCHAR2(36) NOT NULL,
    D_CIUDAD VARCHAR2(36) NOT NULL,
    D_COLONIA VARCHAR2(36) NOT NULL,
    D_ZONA VARCHAR2(36) NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE,
    STATUS NUMBER(2) NOT NULL,
    CREADO_POR VARCHAR2(36) NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP,
    ACTUALIZADO_POR VARCHAR2(36),
    NOTAS VARCHAR2(100),
    ACCION VARCHAR2(20) NOT NULL,
    IP VARCHAR2(30) NOT NULL,
    CONSTRAINT PK_DATOS_FISCALES_ESPEJO PRIMARY KEY (UUID_DATOS_FISCALES_ESPEJO)
);

COMMENT ON TABLE DATOS_FISCALES_ESPEJO IS 'Tabla espejo o bitácora de datos fiscales';
COMMENT ON COLUMN DATOS_FISCALES_ESPEJO.UUID_DATOS_FISCALES_ESPEJO IS 'UUID único del registro espejo';
COMMENT ON COLUMN DATOS_FISCALES_ESPEJO.ID_DATOSFISC IS 'Llave primaria del registro fiscal';
